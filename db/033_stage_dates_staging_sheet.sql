 'One row per problem with a staging line or a stage-dates row. Empty before promotion, or the promotion will refuse the session. Extended at db/015; amended at db/020, where the date_concluded rule became a rule about enactment rather than about passing; at db/028 it also flags an SP Bill number or a stated introduced title left inside short_title; at db/031 it requires a route for every Stage 1 rejection, the announcement that route rests on, and the date the Official Report was read. At db/033 it reads the stage-dates staging sheet: the date checks moved there, and it checks that stage dates run in order, stage names fit the bill type, nothing comes after the stage a bill ended at, two sources for the same stage agree, and a stage completed on a date not known has a note. A problem with a stage-dates row names the stage and its source, and gives the row in stage_candidate_id. A missing date is not a problem; it is listed in v_stage_date_gaps.';

