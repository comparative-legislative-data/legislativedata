UPDATE methodology_note
   SET body = $m2$Each stage of a bill is treated as completed at a fixed point, the same for every bill. Stage 1 is completed on the date of the Stage 1 debate, at which the Parliament decides whether to agree to the bill's general principles. Stage 2 is completed on the date of the meeting at which the last amendments were disposed of. Every bill has such a meeting: where no amendments are lodged, the committee, or for an emergency bill the Parliament sitting as a committee, still meets and agrees to each section, so Stage 2 always has a date. Stage 3 is completed on the date the Parliament votes to pass the bill. A stage a bill did not get through is recorded as not completed; where a decision ended it, such as a vote not to agree to the general principles at Stage 1, it carries the date of that decision.

Private Bills go through a Preliminary Stage, a Consideration Stage and a Final Stage, and are recorded under those names. The Parliament says of them: "These stages are quite different from the stages of a Government Bill, and they have different names." They are compared with a public bill's stages by their position in the sequence, not treated as the same stages, and are taken as completed at the equivalent points. The Preliminary Stage ends on the debate at which "The Parliament then debates the bill and decides whether it should go on to Consideration Stage, or be rejected." The Consideration Stage ends at the meeting of the Private Bill committee at which the last amendments were disposed of. The Final Stage ends on the vote to pass. Hybrid Bills go through Stage 1, 2 and 3, of which the Parliament says: "In most ways, these stages are the same as the stages of a Government Bill, but in other ways are like the stages of a Private Bill." They are taken as completed at the same points as a public bill. Both quotations are from the Parliament's pages "About Private Bills" and "About Hybrid Bills", read on 11 September 2026. Those pages describe the procedure as it is now.

The date a bill was passed is taken from the Parliament's legislation fact sheets. The dates of Stages 1 and 2 are taken from the dataset compiled for Steven MacGregor, "Does government dominate the legislative process?" (PhD thesis, University of Stirling, 2021), which covers Sessions 1 to 6. They are added one session at a time; a session whose dates have not yet been added has no Stage 1 or Stage 2 dates. For a bill rejected at Stage 1, the date is taken from the Official Report, and the thesis dataset is checked against it.

Where a stage was completed but its date could not be established, it is recorded as completed with no date, and a note says why. Durations are measured between consecutive dated points: introduction, each dated stage, and Royal Assent. A bill without a date for a stage gives no figure for that stage. Instead it gives one interval across it, labelled with the stages at either end: a bill with no Stage 2 date gives a Stage 1 to Stage 3 interval, not a Stage 2 duration.$m2$,
